// The Inkbridge window: status, pairing and paired tablets. Talks to the
// app through Tauri commands ("status", "open_pairing", ...) and events.
const { invoke } = window.__TAURI__.core;
const { listen } = window.__TAURI__.event;
const $ = (id) => document.getElementById(id);

let pairingShown = false;

// Asks for confirmation in the page's own dialog (the web view's built-in
// confirm box renders badly and blocks resizing).
function ask(text, okLabel) {
  const dialog = $("ask");
  $("ask-text").textContent = text;
  $("ask-ok").textContent = okLabel;
  return new Promise((resolve) => {
    $("ask-ok").onclick = () => { dialog.close(); resolve(true); };
    $("ask-cancel").onclick = () => { dialog.close(); resolve(false); };
    dialog.oncancel = () => resolve(false); // Esc
    dialog.showModal();
  });
}

function render(s) {
  $("computer").textContent = s.computer;
  const t = s.tablet;
  $("dot").classList.toggle("on", !!t);
  if (t) {
    $("status-title").textContent = `Connected: ${t.name}`;
    const rtt = t.rtt_ms != null ? ` · ${t.rtt_ms.toFixed(0)} ms round trip` : "";
    $("status-detail").textContent = `${t.link} (${t.protocol})${rtt}`;
  } else if (s.paired.length === 0) {
    $("status-title").textContent = "No tablet paired yet";
    $("status-detail").textContent = "Pair your tablet below to start.";
  } else {
    $("status-title").textContent = "Waiting for your tablet";
    $("status-detail").textContent =
      "Open Inkbridge on the tablet and tap this computer, or plug in the USB cable.";
  }
  // The code closes once a tablet used it (or it expired).
  if (pairingShown && !s.pairing_open) showPairing(null);

  const list = $("paired");
  list.replaceChildren();
  // Most recently used first; an older pairing of a tablet with the same
  // name (the app was reinstalled) is marked so it can be forgotten.
  const seen = new Set();
  for (const p of s.paired) {
    const li = document.createElement("li");
    const who = document.createElement("div");
    const name = document.createElement("div");
    name.className = "name";
    name.textContent = p.name;
    const when = document.createElement("div");
    when.className = "muted small";
    when.textContent = `Last used ${p.last_used}` +
      (seen.has(p.name) ? " · older pairing" : "");
    seen.add(p.name);
    who.append(name, when);
    const forget = document.createElement("button");
    forget.className = "link";
    forget.textContent = "Forget";
    forget.onclick = async () => {
      if (await ask(`Forget ${p.name}? It will need a new pairing code to connect.`, "Forget")) {
        await invoke("forget", { fingerprint: p.fingerprint });
        refresh();
      }
    };
    li.append(who, forget);
    list.append(li);
  }
  $("paired-empty").hidden = s.paired.length > 0;
  return s;
}

function showPairing(p) {
  pairingShown = !!p;
  $("pair-idle").hidden = !!p;
  $("pair-open").hidden = !p;
  if (p) {
    $("qr").innerHTML = p.svg; // generated by the app from the pairing code
    $("pair-note").textContent = `The code works once, for ${p.minutes} minutes.`;
  }
}

async function openPairing() {
  try {
    showPairing(await invoke("open_pairing"));
  } catch (e) {
    $("pair-note").textContent = String(e);
  }
}

async function refresh() {
  return render(await invoke("status"));
}

$("pair-button").onclick = openPairing;
$("pair-cancel").onclick = async () => {
  await invoke("close_pairing");
  showPairing(null);
};
$("quit").onclick = () => invoke("quit");

// Advanced options and autostart.
async function loadAdvanced() {
  const a = await invoke("advanced");
  $("autostart").checked = a.autostart;
  $("adb").checked = a.adb;
  const win = a.os === "windows";
  $("extra-screen-win").hidden = !win;
  $("extra-screen-mac").hidden = !(a.os === "macos" && a.extra_screen_installed);
  $("usb-routing").hidden = !win;
  $("extra-screen-state").textContent = a.extra_screen_installed ? "Installed." : "Not installed.";
  $("extra-screen-install").hidden = a.extra_screen_installed;
  $("extra-screen-remove").hidden = !a.extra_screen_installed;
}

async function run(button, command, done) {
  const note = $("advanced-note");
  button.disabled = true;
  note.textContent = "Waiting for the admin prompt…";
  try {
    await invoke(command);
    note.textContent = done;
  } catch (e) {
    note.textContent = String(e);
  }
  button.disabled = false;
  loadAdvanced();
}

$("autostart").onchange = (e) =>
  invoke("set_autostart", { enabled: e.target.checked }).catch((err) => {
    $("advanced-note").textContent = String(err);
    loadAdvanced();
  });
$("adb").onchange = async (e) => {
  $("advanced-note").textContent = "Restarting Inkbridge…";
  try {
    await invoke("set_adb", { enabled: e.target.checked });
    $("advanced-note").textContent = e.target.checked
      ? "USB through adb is on. Plug the tablet in with USB debugging allowed."
      : "USB through adb is off.";
  } catch (err) {
    $("advanced-note").textContent = String(err);
  }
  loadAdvanced();
};
$("extra-screen-install").onclick = (e) =>
  run(e.target, "install_extra_screen", "Installed. Choose \"Extra screen\" in the tablet's Screen menu.");
$("extra-screen-remove").onclick = (e) => run(e.target, "remove_extra_screen", "Removed.");
$("usb-routing-fix").onclick = (e) => run(e.target, "fix_usb_routing", "Done.");
loadAdvanced();

listen("status", (e) => render(e.payload));
listen("pair", () => openPairing());

refresh().then((s) => {
  // First start: nothing paired, so begin with the code.
  if (s.paired.length === 0) openPairing();
});
